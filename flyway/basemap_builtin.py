def _close(ring):
    ring = [list(p) for p in ring]
    if ring[0] != ring[-1]:
        ring.append(list(ring[0]))
    return ring


def build_geojson() -> dict:
    feats = []
    feats.append({"type": "Feature", "properties": {"kind": "land", "name": "Americas"},
                  "geometry": {"type": "Polygon", "coordinates": [_close(AMERICAS)]}})
    for name, ring in {**ISLANDS, **OLD_WORLD_WEST}.items():
        feats.append({"type": "Feature", "properties": {"kind": "land", "name": name},
                      "geometry": {"type": "Polygon", "coordinates": [_close(ring)]}})
    for name, ring in LAKES.items():
        feats.append({"type": "Feature", "properties": {"kind": "lake", "name": name},
                      "geometry": {"type": "Polygon", "coordinates": [_close(ring)]}})
    for name, line in BORDERS.items():
        feats.append({"type": "Feature", "properties": {"kind": "border", "name": name},
                      "geometry": {"type": "LineString", "coordinates": [list(p) for p in line]}})
    return {"type": "FeatureCollection", "features": feats, "properties": {"source": "builtin-simplified"}}
